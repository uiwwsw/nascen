def _scene(group, index, topic, row, *, principle=None, skill=None, pair=None):
    first, second, correct, *distractors = row
    identifier = f"{group}-{index}"
    options = [correct, *distractors]
    if len(options) == 2:
        if sha256(identifier.encode()).digest()[0] % 2:
            options.reverse()
    else:
        Random(identifier).shuffle(options)
    return Scene(identifier, group, topic, (first, second), tuple(options), options.index(correct), principle, skill, pair)


def splits() -> tuple[tuple[Scene, ...], tuple[Scene, ...]]:
    train = tuple(_scene(group, i, "physical" if rule in ("push", "latch") else "social", row, principle=rule)
                  for group, rule, *rows in TRAINING for i, row in enumerate(rows))
    exam = tuple(_scene(group, i, topic, row, skill=skill,
                        pair=group if skill in ("paraphrase", "exception") else None)
                 for group, topic, skill, *rows in EXAM for i, row in enumerate(rows))
    return train, exam


def budget_scenes(scenes: tuple[Scene, ...], groups_per_principle: int) -> tuple[Scene, ...]:
    groups = {rule: [] for rule in PRINCIPLES}
    for row in scenes:
        selected = groups[row.principle]
        if row.group not in selected and len(selected) < groups_per_principle:
            selected.append(row.group)
    return tuple(row for row in scenes if row.group in groups[row.principle])


def digest(value) -> str:
    return sha256(json.dumps(value, ensure_ascii=False, sort_keys=True).encode()).hexdigest()


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        try:
            json.dump(value, stream, ensure_ascii=False, indent=2, allow_nan=False)
            stream.write("\n")
            stream.close()
            temporary.replace(path)
        finally:
            temporary.unlink(missing_ok=True)
